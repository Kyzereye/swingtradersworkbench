/**
 * Writes test fixtures from the dev database. Runs SELECTs only.
 *
 *   node tests/tools/export-fixtures.mjs
 *
 * Output:
 *   tests/fixtures/bars/<SYMBOL>.json  bars for the unit tests
 *   tests/fixtures/seed.sql            the same symbols and bars, for StockPxLabs_test
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { getPool, closePool } from "../../backend/src/db.js";
import { loadBarsForSymbol } from "../../backend/src/scanData.js";

const SYMBOLS = ["AAPL", "MSFT", "SPY"];
const INSERT_BATCH_SIZE = 500;

const fixturesDir = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "fixtures");
const barsDir = path.join(fixturesDir, "bars");

async function loadSymbolRow(symbol) {
  const [rows] = await getPool().query(
    "SELECT symbol, company_name, asset_type, exchange FROM stock_symbols WHERE symbol = ?",
    [symbol]
  );
  if (rows.length === 0) {
    throw new Error(`Symbol ${symbol} is not in the database.`);
  }
  return rows[0];
}

function symbolInsertSql(symbolRow) {
  const pool = getPool();
  const values = [
    symbolRow.symbol,
    symbolRow.company_name,
    symbolRow.asset_type,
    symbolRow.exchange,
  ].map((value) => pool.escape(value));
  return `INSERT IGNORE INTO stock_symbols (symbol, company_name, asset_type, exchange) VALUES (${values.join(", ")});`;
}

function barInsertSql(symbol, bars) {
  const pool = getPool();
  const symbolId = `(SELECT id FROM stock_symbols WHERE symbol = ${pool.escape(symbol)})`;
  const statements = [];
  for (let start = 0; start < bars.length; start += INSERT_BATCH_SIZE) {
    const batch = bars.slice(start, start + INSERT_BATCH_SIZE);
    const rows = batch.map((bar) => {
      const values = [bar.date, bar.open, bar.high, bar.low, bar.close, bar.volume];
      return `(@symbol_id, ${values.map((value) => pool.escape(value)).join(", ")})`;
    });
    statements.push(
      `INSERT IGNORE INTO daily_stock_data (symbol_id, date, open, high, low, close, volume) VALUES\n${rows.join(",\n")};`
    );
  }
  return [`SET @symbol_id = ${symbolId};`, ...statements].join("\n");
}

async function main() {
  fs.mkdirSync(barsDir, { recursive: true });

  const seedParts = [
    "-- Test seed for StockPxLabs_test. Generated by tests/tools/export-fixtures.mjs.",
    "-- Load into the test database only, after sql_queries/sql_queries.sql.",
  ];

  for (const symbol of SYMBOLS) {
    const symbolRow = await loadSymbolRow(symbol);
    const bars = await loadBarsForSymbol(symbol);

    fs.writeFileSync(path.join(barsDir, `${symbol}.json`), JSON.stringify(bars));
    seedParts.push("", `-- ${symbol}: ${bars.length} bars`, symbolInsertSql(symbolRow), barInsertSql(symbol, bars));

    console.log(`${symbol}: ${bars.length} bars, ${bars[0].date} to ${bars[bars.length - 1].date}`);
  }

  fs.writeFileSync(path.join(fixturesDir, "seed.sql"), seedParts.join("\n") + "\n");
  console.log(`Wrote ${barsDir} and ${path.join(fixturesDir, "seed.sql")}`);
}

try {
  await main();
} finally {
  await closePool();
}
